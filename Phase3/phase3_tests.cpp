#include "phase3_rounak_cli.hpp"
#include <sstream>
int passed = 0, failed = 0;
void check(bool ok, string what){
    if(ok) { cout << "   PASS: " << what << "\n"; passed++; }
    else{ cout << "   FAIL: " << what << "\n"; failed++; }
}
void startTest(string title){
    cout << "\n===== " << title << " =====\n";
    setupFileSystem();
}
bool realFileExists(string path){
    ifstream file(path.c_str());
    return file.good();
}
string textOf(string name){
    int i = findInCurrent(name);
    if(i == -1) return "<missing>";
    return loadText(inodes[i].blocks, inodes[i].size);
}
int main(){
    realRoot = "test_root";
    useSaveFile = false;
    startTest("TEST 1: touch");
    cmdTouch("a.txt");
    check(findInCurrent("a.txt") == 1, "a.txt got inode 1");
    check(realFileExists("test_root/a.txt"), "real file test_root/a.txt was created");
    startTest("TEST 2: mkdir, cd, pwd path");
    cmdMakedir("docs");
    cmdCd("docs", "");
    check(pathOf(currentFolder) == "/docs", "we are in /docs");
    cmdTouch("inside.txt");
    check(realFileExists("test_root/docs/inside.txt"), "real file created inside docs");
    cmdCd("..", "");
    check(currentFolder == 0, "cd .. goes back to root");
    startTest("TEST 3: write and cat");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "hello world");
    check(textOf("a.txt") == "hello world", "same text comes back");
    check(inodes[findInCurrent("a.txt")].blocks.size() == 1, "11 characters use 1 block");
    startTest("TEST 4: long text uses many blocks");
    string longText = "";
    for(int k = 0; k < 2 * BLOCK_SIZE + 6; k++) longText += (char)('a' + k % 26);
    cmdTouch("big.txt");
    cmdWrite("big.txt", longText);
    check(inodes[findInCurrent("big.txt")].blocks.size() == 3, "2 full blocks + 6 characters use 3 blocks");
    check(textOf("big.txt") == longText, "all 3 blocks read back in order");
    startTest("TEST 5: append");
    cmdTouch("log.txt");
    cmdWrite("log.txt", "line1 ");
    cmdAppend("log.txt", "line2");
    check(textOf("log.txt") == "line1 line2", "text added at the end");
    startTest("TEST 6: cp makes an independent copy");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "original");
    cmdCp("a.txt", "b.txt");
    cmdWrite("a.txt", "changed");
    check(textOf("b.txt") == "original", "copy did not change");
    check(inodes[findInCurrent("a.txt")].blocks[0] != inodes[findInCurrent("b.txt")].blocks[0],
          "copy has its own block");
    startTest("TEST 7: mv rename and move into folder");
    cmdTouch("old.txt");
    int ino = findInCurrent("old.txt");
    cmdMv("old.txt", "new.txt");
    check(findInCurrent("new.txt") == ino, "rename keeps the same inode");
    check(realFileExists("test_root/new.txt"), "real file renamed too");
    cmdMakedir("box");
    cmdMv("new.txt", "box");
    check(inodes[ino].parent == findInCurrent("box"), "move changes the parent number");
    check(realFileExists("test_root/box/new.txt"), "real file moved too");
    startTest("TEST 8: rm gives back block and inode");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "bye");
    cmdRm("a.txt", "");
    check(countFreeBlocks() == TOTAL_BLOCKS, "block is free again");
    check(getFreeInode() == 1, "inode 1 is free again");
    check(realFileExists("test_root/a.txt") == false, "real file deleted");
    startTest("TEST 9: rm refuses a folder that is not empty");
    cmdMakedir("docs");
    cmdCd("docs", "");
    cmdTouch("x.txt");
    cmdCd("..", "");
    cmdRm("docs", "");
    check(findInCurrent("docs") != -1, "docs still exists");
    startTest("TEST 10: chmod read-only");
    cmdTouch("cfg.txt");
    cmdWrite("cfg.txt", "original");
    cmdChmod("cfg.txt", "ro");
    cmdWrite("cfg.txt", "hacked");
    cmdAppend("cfg.txt", "more");
    cmdRm("cfg.txt", "");
    cmdMv("cfg.txt", "other.txt");
    check(textOf("cfg.txt") == "original", "write, append, rm and mv were all refused");
    cmdChmod("cfg.txt", "rw");
    cmdRm("cfg.txt", "");
    check(findInCurrent("cfg.txt") == -1, "rm works after chmod rw");
    startTest("TEST 11: lock and unlock");
    cmdMakedir("secret");
    cmdLock("secret", "pass123");
    cmdCd("secret", "");
    check(currentFolder == 0, "cd without password refused");
    cmdCd("secret", "wrong");
    check(currentFolder == 0, "cd with wrong password refused");
    cmdCd("secret", "pass123");
    check(pathOf(currentFolder) == "/secret", "cd with correct password works");
    cmdCd("..", "");
    cmdRm("secret", "");
    check(findInCurrent("secret") != -1, "rm without password refused");
    cmdUnlock("secret", "pass123");
    cmdCd("secret", "");
    check(pathOf(currentFolder) == "/secret", "after unlock no password is needed");
    startTest("TEST 12: find uses the hash index");
    cmdMakedir("docs");
    cmdCd("docs", "");
    cmdTouch("a.txt");
    cmdCd("/", "");
    rebuildIndex();
    check(pathIndex.count("/docs/a.txt") == 1, "/docs/a.txt is in the hash index");
    check(pathIndex["/docs/a.txt"] == 2, "it points to inode 2");
    cmdMv("docs", "papers");
    rebuildIndex();
    check(pathIndex.count("/docs/a.txt") == 0 && pathIndex.count("/papers/a.txt") == 1,
          "after renaming the folder, the path of the file is updated");
    startTest("TEST 13: Rahul and rahul are the same name");
    cmdMakedir("Rahul");
    cmdMakedir("rahul");
    check(getFreeInode() == 2, "second mkdir was refused");
    cmdCd("RAHUL", "");
    check(pathOf(currentFolder) == "/Rahul", "cd RAHUL enters Rahul, name shown as typed");
    startTest("TEST 14: wrong names are refused");
    cmdMakedir("a/b");
    cmdTouch("..");
    check(getFreeInode() == 1, "nothing was created");
    startTest("TEST 15: (changed in Phase 3) a file bigger than 64 blocks now fits");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "original");
    string big(TOTAL_BLOCKS * BLOCK_SIZE + 1, 'z');
    cmdWrite("a.txt", big);
    check(textOf("a.txt") == big, "big text was stored (Phase 2 refused it)");
    startTest("TEST 16: everything comes back after a restart");
    useSaveFile = true;
    saveFileName = "test_save.txt";
    remove(saveFileName.c_str());
    setupFileSystem();
    cmdMakedir("docs");
    cmdLock("docs", "pw");
    cmdCd("docs", "pw");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "hello again");
    cmdChmod("a.txt", "ro");
    saveFileSystem();
    setupFileSystem();
    int docs = findInCurrent("docs");
    check(docs != -1 && inodes[docs].password == "pw", "locked folder came back with its password");
    cmdCd("docs", "pw");
    int a = findInCurrent("a.txt");
    check(a != -1 && textOf("a.txt") == "hello again", "file and its text came back");
    check(a != -1 && inodes[a].readOnly, "read-only came back");
    check(countFreeBlocks() == TOTAL_BLOCKS - 1, "its block is marked used again");
    check(realFileExists("test_root/docs/a.txt"), "real file is rebuilt in test_root");
    remove(saveFileName.c_str());
    useSaveFile = false;
    startTest("TEST 17: cache - second read is a HIT");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "hello");
    cmdCat("a.txt");
    cmdCat("a.txt");
    check(cache.getMisses() == 1, "first read was a miss");
    check(cache.getHits() == 1, "second read was a hit");
    startTest("TEST 18: cache - least recently used block is thrown out");
    cmdTouch("f0"); cmdWrite("f0", "zero");
    cmdTouch("f1"); cmdWrite("f1", "one");
    cmdTouch("f2"); cmdWrite("f2", "two");
    cmdTouch("f3"); cmdWrite("f3", "three");
    cmdTouch("f4"); cmdWrite("f4", "four");
    cmdCat("f0"); cmdCat("f1"); cmdCat("f2"); cmdCat("f3");
    cmdCat("f4");
    cmdCat("f1");
    check(cache.getHits() == 1, "f1 was still in the cache");
    cmdCat("f0");
    check(cache.getMisses() == 6, "f0 had been thrown out, so it was a miss again");
    startTest("TEST 19: cache - deleted file leaves the cache, no old data");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "OLD");
    cmdCat("a.txt");
    check(cache.usedSlots() == 1, "block is in the cache");
    cmdWrite("a.txt", "NEW");
    check(cache.usedSlots() == 0, "freed block was removed from the cache");
    check(loadTextCached(inodes[findInCurrent("a.txt")].blocks, 3) == "NEW", "cat shows the new text");
    startTest("TEST 20: growing disk - 64 -> 128 blocks");
    cmdTouch("big.txt");
    cmdWrite("big.txt", string(3000, 'x'));
    check(totalBlocks == 128, "disk grew to 128 blocks");
    check(inodes[findInCurrent("big.txt")].blocks.size() == 94, "file uses 94 blocks");
    check(countFreeBlocks() == 128 - 94, "the rest is free");
    startTest("TEST 21: growing disk - too big for MAX_BLOCKS is still refused");
    cmdTouch("a.txt");
    cmdWrite("a.txt", "original");
    cmdWrite("a.txt", string(MAX_BLOCKS * BLOCK_SIZE + 1, 'z'));
    check(textOf("a.txt") == "original", "old text kept");
    check(totalBlocks == TOTAL_BLOCKS, "disk did not grow for a write that failed");
    startTest("TEST 22: save file - disk size is saved (VFS3)");
    useSaveFile = true;
    saveFileName = "test_save3.txt";
    remove(saveFileName.c_str());
    setupFileSystem();
    cmdTouch("big.txt");
    cmdWrite("big.txt", string(3000, 'y'));
    saveFileSystem();
    setupFileSystem();
    check(totalBlocks == 128, "disk size came back");
    check(textOf("big.txt") == string(3000, 'y'), "big file came back");
    remove(saveFileName.c_str());
    startTest("TEST 23: a Phase 2 save file (VFS2) still opens");
    {
        ofstream old(saveFileName.c_str());
        old << "VFS2\n2\n1 docs 1 0 0 0 - 0\n\n2 a.txt 0 1 5 0 - 1 0\nhello\n";
    }
    setupFileSystem();
    check(findInCurrent("docs") != -1, "folder from Phase 2 file is there");
    cmdCd("docs", "");
    check(textOf("a.txt") == "hello", "file from Phase 2 file is there");
    check(totalBlocks == TOTAL_BLOCKS, "disk starts at 64 blocks");
    remove(saveFileName.c_str());
    useSaveFile = false;
    journal.setFile("test_journal.txt");
    startTest("TEST 24: journal - BEGIN and COMMIT, no password");
    journal.clearAll();
    {
        Phase3Shell shell;
        shell.runLine("makedir docs");
        shell.runLine("seal docs pass123");
        shell.runLine("items");
    }
    check(journal.size() == 4, "2 changing commands = 4 entries (items is not logged)");
    check(journal.entry(0) == "BEGIN    makedir docs", "first entry is BEGIN");
    check(journal.entry(1) == "COMMIT   makedir docs", "second entry is COMMIT");
    bool leaked = false;
    for(int k = 0; k < journal.size(); k++){
        if(journal.entry(k).find("pass123") != string::npos) leaked = true;
    }
    check(leaked == false, "password is not in the journal");
    startTest("TEST 25: crash and recover");
    journal.clearAll();
    {
        Phase3Shell shell;
        journal.crash("store a.txt");
        shell.runLine("makedir blocked");
        check(findInCurrent("blocked") == -1, "changes refused after a crash");
        Journal reloaded;
        reloaded.setFile("test_journal.txt");
        reloaded.load();
        check(reloaded.isCrashed(), "crash is remembered after a restart");
        journal.recover();
        check(journal.entry(journal.size() - 1) == "ROLLBACK store a.txt", "last entry is ROLLBACK");
        shell.runLine("makedir works");
        check(findInCurrent("works") != -1, "changes work again after recover");
    }
    journal.clearAll();
    remove("test_journal.txt");
    startTest("TEST 26: FolderExplorer - layout and seek");
    cmdMakedir("docs");
    cmdCd("docs", "");
    cmdTouch("a.txt");
    cmdCd("..", "");
    cmdTouch("a.txt");
    cmdMakedir("secret");
    cmdCd("secret", "");
    cmdTouch("a.txt");
    cmdCd("..", "");
    cmdLock("secret", "pw");
    stringstream out;
    streambuf* screen = cout.rdbuf(out.rdbuf());
    explorer.seek("A.TXT");
    int found = explorer.lastFound();
    explorer.showLayout(currentFolder);
    cout.rdbuf(screen);
    string printed = out.str();
    check(found == 2, "seek finds a.txt in 2 folders (not in the locked one)");
    check(printed.find("/docs/a.txt") != string::npos && printed.find("/a.txt") != string::npos,
          "seek prints the full paths");
    check(printed.find("/secret/a.txt") == string::npos, "seek does not look inside a locked folder");
    check(printed.find("|-- docs/") != string::npos && printed.find("[locked]") != string::npos,
          "layout shows folders and marks the locked one");
    check(explorer.lastShown() == 4, "layout showed 4 items (docs, a.txt inside docs, a.txt, secret)");
    startTest("TEST 27: new unique command names");
    {
        Phase3Shell shell;
        stringstream out2;
        streambuf* screen2 = cout.rdbuf(out2.rdbuf());
        shell.runLine("tree");
        shell.runLine("search a.txt");
        shell.runLine("stats");
        cout.rdbuf(screen2);
        string oldNames = out2.str();
        stringstream out3;
        screen2 = cout.rdbuf(out3.rdbuf());
        shell.runLine("makedir docs");
        shell.runLine("layout");
        shell.runLine("seek docs");
        shell.runLine("health");
        cout.rdbuf(screen2);
        string newNames = out3.str();
        int unknown = 0;
        for(size_t pos = oldNames.find("Unknown command"); pos != string::npos;
             pos = oldNames.find("Unknown command", pos + 1)) unknown++;
        check(unknown == 3, "old names tree, search, stats are unknown now");
        check(newNames.find("`-- docs/") != string::npos, "layout works (docs is the only, so last, item)");
        check(newNames.find("/docs   (folder)") != string::npos, "seek works");
        check(newNames.find("Disk        :") != string::npos, "health works");
    }
    journal.clearAll();
    remove("test_journal.txt");
    realDeleteAll();
    cout << "\nPASSED: " << passed << "   FAILED: " << failed << "\n";
    return 0;
}